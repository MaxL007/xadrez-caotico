const TEXTOS: Record<Idioma, Record<ChaveTexto, string>> = { 'pt-BR': PT, en: EN, es: ES }

export type Traduzir = (chave: ChaveTexto, valores?: Record<string, string | number>) => string

export function tradutor(idioma: Idioma): Traduzir {
  const textos = TEXTOS[idioma] ?? PT
  return (chave, valores) => {
    let texto = textos[chave]
    for (const [nome, valor] of Object.entries(valores ?? {})) texto = texto.replace(`{${nome}}`, String(valor))
    return texto
  }
}
